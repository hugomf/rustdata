use crate::{
    entity::expand_derive, projection_derive::expand_projection, sql_type_derive::expand_sql_type,
};

fn parse_struct(input: proc_macro2::TokenStream) -> syn::DeriveInput {
    syn::parse2(input).unwrap()
}

// ─── Entity ─────────────────────────────────────────────────────

#[test]
fn entity_basic() {
    let input = parse_struct(quote::quote! {
        #[entity(table = "users")]
        struct User {
            #[entity(id)]
            id: uuid::Uuid,
            email: String,
            name: String,
        }
    });
    let output = expand_derive(input).to_string();
    assert!(output.contains("EntityDescriptor for User"));
    assert!(output.contains(r#"const TABLE : & 'static str = "users""#));
    assert!(output.contains("type Id = uuid :: Uuid"));
    assert!(output.contains("pub type UserRepo = :: rustdata_core :: repo :: CrudRepository"));
}

