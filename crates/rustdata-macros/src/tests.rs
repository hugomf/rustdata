// ─── Projection ─────────────────────────────────────────────────

#[test]
fn projection_basic() {
    let input = parse_struct(quote::quote! {
        struct UserName {
            id: uuid::Uuid,
            name: String,
        }
    });
    let output = expand_projection(input).to_string();
    assert!(output.contains("impl :: rustdata_core :: projection :: Projection for UserName"));
    assert!(output.contains("type Entity = UserName"));
    assert!(output.contains("ColumnDef :: new (\"id\" ,"));
    assert!(output.contains("ColumnDef :: new (\"name\" ,"));
}

#[test]
fn projection_with_multiple_types() {
    let input = parse_struct(quote::quote! {
        struct UserProfile {
            id: uuid::Uuid,
            email: String,
            age: i32,
            score: i64,
            active: bool,
            created_at: chrono::DateTime<chrono::Utc>,
        }
    });
    let output = expand_projection(input).to_string();
    assert!(output.contains("SqlTypeId :: Uuid"));
    assert!(output.contains("SqlTypeId :: Varchar"));
    assert!(output.contains("SqlTypeId :: Int"));
    assert!(output.contains("SqlTypeId :: BigInt"));
    assert!(output.contains("SqlTypeId :: Boolean"));
    assert!(output.contains("SqlTypeId :: TimestampTz"));
}
